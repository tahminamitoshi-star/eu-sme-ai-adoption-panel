"""
01_clean_data.py
Builds the clean country x year x size-class panel for the paper
"AI-Enabled Digital Transformation and Sustainable SME Growth".

Input  (never modified): ../03_data_raw/*.csv  (Eurostat SDMX-CSV, labels only)
Output: ../04_data_clean/panel_clean.csv        analysis panel, EU-27 member states
        ../04_data_clean/eu27_aggregate.csv     EU-27 averages, descriptive use only
        ../04_data_clean/ai_2025_descriptive.csv AI use 2025, descriptive use only
        ../04_data_clean/cleaning_report.txt    checks run on the data

Run from the 05_analysis folder:  python 01_clean_data.py
Every rule applied below is recorded in Project_Log.xlsx (Decision log).
"""

from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "03_data_raw"
OUT = ROOT / "04_data_clean"
OUT.mkdir(exist_ok=True)

FILES = {
    "ai": RAW / "isoc_eb_ai_raw_2026-10-10.csv",
    "dii": RAW / "isoc_e_dii_raw_2026-10-10.csv",
    "sbs": RAW / "sbs_sc_ovw_raw_2026-10-10.csv",
    "gdp": RAW / "nama_10_gdp_raw_2026-10-10.csv",
}

YEARS = [2021, 2023, 2024]  # Decision log: common years
EU_LABEL = "European Union - 27 countries (from 2020)"

# Eurostat labels -> ISO codes (all four files use exactly these 28 labels)
GEO = {
    EU_LABEL: "EU27_2020", "Belgium": "BE", "Bulgaria": "BG", "Czechia": "CZ",
    "Denmark": "DK", "Germany": "DE", "Estonia": "EE", "Ireland": "IE",
    "Greece": "EL", "Spain": "ES", "France": "FR", "Croatia": "HR",
    "Italy": "IT", "Cyprus": "CY", "Latvia": "LV", "Lithuania": "LT",
    "Luxembourg": "LU", "Hungary": "HU", "Malta": "MT", "Netherlands": "NL",
    "Austria": "AT", "Poland": "PL", "Portugal": "PT", "Romania": "RO",
    "Slovenia": "SI", "Slovakia": "SK", "Finland": "FI", "Sweden": "SE",
}
SIZE = {
    "From 10 to 19 persons employed": "10-19",
    "From 20 to 49 persons employed": "20-49",
    "From 10 to 49 persons employed": "10-49",
    "From 50 to 249 persons employed": "50-249",
    "250 persons employed or more": "GE250",
}
SBS_AGG = ("Industry, construction and market services (except public "
           "administration and defence; compulsory social security; "
           "activities of membership organisations)")

report = []


def log(text=""):
    report.append(str(text))
    print(text)


def load(key):
    df = pd.read_csv(FILES[key])
    unknown = set(df["geo"]) - set(GEO)
    if unknown:
        raise ValueError(f"{key}: unexpected country labels {unknown}")
    df["geo_code"] = df["geo"].map(GEO)
    if "size_emp" in df:
        df["size"] = df["size_emp"].map(SIZE)
        if df["size"].isna().any():
            raise ValueError(f"{key}: unexpected size class labels")
    df["flag"] = df["OBS_FLAG"].fillna("")
    log(f"{key}: {len(df):,} rows read from {FILES[key].name}")
    return df


log("CLEANING REPORT  (generated by 01_clean_data.py)")
log("=" * 60)

# ---------------------------------------------------------------- AI
ai = load("ai")
ind = ai["indic_is"]
ai["var"] = np.select(
    [ind.str.startswith("Enterprises using at least one of the AI"),
     ind.str.contains("costs seem too high"),
     ind.str.contains("lack of relevant expertise")],
    ["ai_use", "ai_barrier_cost", "ai_barrier_expertise"], default="")
if (ai["var"] == "").any():
    raise ValueError("ai: unexpected indicator")
ai_w = ai.pivot_table(index=["geo_code", "TIME_PERIOD", "size"], columns="var",
                      values="OBS_VALUE", aggfunc="first")
ai_flag = (ai[ai["var"] == "ai_use"]
           .set_index(["geo_code", "TIME_PERIOD", "size"])["flag"]
           .rename("ai_use_flag"))
ai_w = ai_w.join(ai_flag)

# ---------------------------------------------------------------- DII
dii = load("dii")
dii = dii[dii["indic_is"].str.contains("DII Version 3")]  # Decision log: V3 only
dii_w = (dii.set_index(["geo_code", "TIME_PERIOD", "size"])[["OBS_VALUE", "flag"]]
         .rename(columns={"OBS_VALUE": "dii_basic", "flag": "dii_flag"}))
# carry the 2023 value forward to 2024 (Decision log)
carry = dii_w.xs(2023, level="TIME_PERIOD").copy()
carry["dii_flag"] = carry["dii_flag"]
carry["TIME_PERIOD"] = 2024
carry = carry.reset_index().set_index(["geo_code", "TIME_PERIOD", "size"])
if dii_w.xs(2024, level="TIME_PERIOD")["dii_basic"].notna().any():
    raise ValueError("dii: V3 unexpectedly has 2024 values; revisit decision")
dii_w = dii_w.drop(index=2024, level="TIME_PERIOD")
dii_w = pd.concat([dii_w, carry])
dii_w["dii_carried_forward"] = (dii_w.index.get_level_values("TIME_PERIOD") == 2024).astype(int)

# ---------------------------------------------------------------- SBS
sbs = load("sbs")
sbs = sbs[sbs["nace_r2"] == SBS_AGG]  # Decision log: aggregate B-S_X_O_S94
sbs["var"] = sbs["indic_sbs"].map({
    "Value added - million euro": "va_meur",
    "Persons employed - number": "emp",
    "Enterprises - number": "ent",
    "Apparent labour productivity - thousand euro": "lp_eurostat_teur",
})
sbs_v = sbs.pivot_table(index=["geo_code", "TIME_PERIOD", "size"], columns="var",
                        values="OBS_VALUE", aggfunc="first")
sbs_f = sbs.pivot_table(index=["geo_code", "TIME_PERIOD", "size"], columns="var",
                        values="flag", aggfunc="first")
sbs_flag = (sbs_f[["va_meur", "emp"]].fillna("").agg(
    lambda r: "".join(sorted(set("".join(r)))), axis=1).rename("sbs_flag"))
sbs_w = sbs_v.join(sbs_flag)

# build 10-49 = (10-19) + (20-49); missing if either part is missing
a = sbs_w.xs("10-19", level="size")
b = sbs_w.xs("20-49", level="size")
small = pd.DataFrame(index=a.index)
for col in ["va_meur", "emp", "ent"]:
    small[col] = a[col] + b[col]  # NaN if either part is NaN
small["lp_eurostat_teur"] = np.nan  # not published for 10-49
small["sbs_flag"] = [
    "".join(sorted(set(x + y))) for x, y in zip(a["sbs_flag"], b["sbs_flag"])]
small["size"] = "10-49"
small = small.reset_index().set_index(["geo_code", "TIME_PERIOD", "size"])
sbs_w = pd.concat([sbs_w.drop(index=["10-19", "20-49"], level="size"), small])

# ---------------------------------------------------------------- GDP
gdp = load("gdp")
gdp["var"] = gdp["unit"].map({
    "Chain linked volumes, percentage change on previous period": "gdp_growth",
    "Price index (implicit deflator), 2020=100, euro": "deflator_2020",
})
gdp_w = gdp.pivot_table(index=["geo_code", "TIME_PERIOD"], columns="var",
                        values="OBS_VALUE", aggfunc="first")
gdp_w["gdp_provisional"] = (gdp[gdp["var"] == "gdp_growth"]
                            .set_index(["geo_code", "TIME_PERIOD"])["flag"]
                            .str.contains("p").astype(int))

# ---------------------------------------------------------------- MERGE
idx = pd.MultiIndex.from_product(
    [sorted(GEO.values()), YEARS, ["10-49", "50-249", "GE250"]],
    names=["geo_code", "TIME_PERIOD", "size"])
panel = (pd.DataFrame(index=idx)
         .join(ai_w).join(dii_w).join(sbs_w)
         .join(gdp_w, on=["geo_code", "TIME_PERIOD"]))

# real value added (2020 euro) and real labour productivity (thousand 2020 euro)
panel["va_real_meur"] = panel["va_meur"] / panel["deflator_2020"] * 100
panel["lp_real_teur"] = panel["va_real_meur"] * 1000 / panel["emp"]
panel["lp_nominal_teur"] = panel["va_meur"] * 1000 / panel["emp"]

# robustness markers (Decision log)
panel["break_flag_any"] = (
    panel[["ai_use_flag", "dii_flag", "sbs_flag"]].fillna("")
    .apply(lambda r: int("b" in "".join(r)), axis=1))
panel["fr_se"] = panel.index.get_level_values("geo_code").isin(["FR", "SE"]).astype(int)

panel = panel.reset_index().rename(columns={"TIME_PERIOD": "year"})
panel["country"] = panel["geo_code"].map({v: k for k, v in GEO.items()})
order = ["geo_code", "country", "year", "size",
         "ai_use", "dii_basic", "dii_carried_forward",
         "va_meur", "va_real_meur", "emp", "ent",
         "lp_nominal_teur", "lp_real_teur", "lp_eurostat_teur",
         "gdp_growth", "deflator_2020",
         "ai_barrier_cost", "ai_barrier_expertise",
         "ai_use_flag", "dii_flag", "sbs_flag", "gdp_provisional",
         "break_flag_any", "fr_se"]
panel = panel[order].sort_values(["geo_code", "size", "year"])

eu = panel[panel["geo_code"] == "EU27_2020"]
countries = panel[panel["geo_code"] != "EU27_2020"]

# AI 2025, descriptive only (Decision log)
ai25 = (ai_w.xs(2025, level="TIME_PERIOD").reset_index()
        .assign(country=lambda d: d["geo_code"].map({v: k for k, v in GEO.items()})))

# ---------------------------------------------------------------- CHECKS
log()
log("CHECKS")
log("-" * 60)
n_exp = 27 * len(YEARS) * 3
log(f"Panel rows (27 countries x 3 years x 3 sizes): {len(countries)} (expected {n_exp})")
assert len(countries) == n_exp

# 1. 10-49 built correctly: sum of parts
raw = sbs[sbs["var"] == "emp"].set_index(["geo_code", "TIME_PERIOD", "size"])["OBS_VALUE"]
chk = countries[countries["size"] == "10-49"].dropna(subset=["emp"])
diffs = [abs(r.emp - raw[(r.geo_code, r.year, "10-19")] - raw[(r.geo_code, r.year, "20-49")])
         for r in chk.itertuples()]
log(f"10-49 employment = (10-19) + (20-49): max difference {max(diffs):.6f} over {len(diffs)} cells")
assert max(diffs) < 1e-6

# 2. computed productivity vs Eurostat's own figure (50-249, GE250)
c = countries.dropna(subset=["lp_nominal_teur", "lp_eurostat_teur"])
pct = ((c["lp_nominal_teur"] - c["lp_eurostat_teur"]) / c["lp_eurostat_teur"] * 100).abs()
log(f"Nominal productivity vs Eurostat LABPRY_TEUR: max abs difference {pct.max():.3f}% over {len(c)} cells")
assert pct.max() < 0.5

# 3. DII carry-forward
cf = countries[countries["year"] == 2024]
same = (cf.set_index(["geo_code", "size"])["dii_basic"]
        .equals(countries[countries["year"] == 2023].set_index(["geo_code", "size"])["dii_basic"]))
log(f"DII 2024 equals DII 2023 for every country and size: {same}")
assert same

# 4. missing values per variable
log()
log("Missing values (27 countries x 3 years x 3 sizes = 243 rows)")
for col in ["ai_use", "dii_basic", "va_real_meur", "emp", "lp_real_teur", "gdp_growth"]:
    miss = countries[countries[col].isna()]
    cells = ", ".join(f"{r.geo_code} {r.year} {r.size}" for r in miss.itertuples())
    log(f"  {col:<14} {len(miss):>3} missing" + (f": {cells}" if cells else ""))

complete = countries.dropna(subset=["ai_use", "dii_basic", "lp_real_teur", "emp", "gdp_growth"])
log()
log("Rows with every main variable present, by size class:")
for s, n in complete.groupby("size").size().items():
    log(f"  {s:<7} {n} of 81")

# 5. flags
log()
log("Rows with a break-in-series flag ('b') in any source:")
for r in countries[countries["break_flag_any"] == 1].itertuples():
    log(f"  {r.geo_code} {r.year} {r.size}  ai='{r.ai_use_flag}' dii='{r.dii_flag}' sbs='{r.sbs_flag}'")
log(f"Rows with provisional GDP figures: {countries['gdp_provisional'].sum()}")

# ---------------------------------------------------------------- SAVE
countries.to_csv(OUT / "panel_clean.csv", index=False)
eu.to_csv(OUT / "eu27_aggregate.csv", index=False)
ai25.to_csv(OUT / "ai_2025_descriptive.csv", index=False)
log()
log("Saved: panel_clean.csv, eu27_aggregate.csv, ai_2025_descriptive.csv")
(OUT / "cleaning_report.txt").write_text("\n".join(report), encoding="utf-8")
