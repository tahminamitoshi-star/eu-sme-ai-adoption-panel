"""
02_analysis.py
Descriptive analysis, main fixed-effects regressions and pre-registered robustness
checks for "AI-Enabled Digital Transformation and Sustainable SME Growth".

Input : ../04_data_clean/panel_clean.csv, eu27_aggregate.csv, ai_2025_descriptive.csv
Output: ../05_analysis/output/  (tables as CSV, figures as PNG, results_report.txt)

Model (Protocol section 5), estimated separately for each size class:
    y_it = b * AI_it + g1 * DII_it + g2 * GDPgrowth_it + country FE + year FE + e_it
    y = ln(real labour productivity) or ln(persons employed)
    Standard errors clustered by country (27 clusters).
Claim type: association, not causation.

Run from the 05_analysis folder:  python 02_analysis.py
"""

from pathlib import Path
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent.parent
CLEAN = ROOT / "04_data_clean"
OUT = ROOT / "05_analysis" / "output"
OUT.mkdir(parents=True, exist_ok=True)

SIZES = ["10-49", "50-249", "GE250"]
SIZE_LABEL = {"10-49": "Small (10-49)", "50-249": "Medium (50-249)", "GE250": "Large (250+)"}
report = []


def log(text=""):
    report.append(str(text))
    print(text)


panel = pd.read_csv(CLEAN / "panel_clean.csv")
eu = pd.read_csv(CLEAN / "eu27_aggregate.csv")
ai25 = pd.read_csv(CLEAN / "ai_2025_descriptive.csv")
panel["ln_lp"] = np.log(panel["lp_real_teur"])
panel["ln_emp"] = np.log(panel["emp"])

log("RESULTS REPORT  (generated by 02_analysis.py)")
log("=" * 70)

# ------------------------------------------------------------ 1. DESCRIPTIVES
log("\n1. DESCRIPTIVE STATISTICS (27 countries; unweighted country values)")
desc_vars = {"ai_use": "AI use (% of enterprises)",
             "dii_basic": "At least basic digital intensity (%)",
             "lp_real_teur": "Real labour productivity (thousand 2020 EUR)",
             "emp": "Persons employed",
             "gdp_growth": "Real GDP growth (%)"}
rows = []
for s in SIZES:
    sub = panel[panel["size"] == s]
    for v, lab in desc_vars.items():
        x = sub[v].dropna()
        # within-country SD: spread of values around each country's own mean
        within = (sub[v] - sub.groupby("geo_code")[v].transform("mean")).dropna()
        rows.append([SIZE_LABEL[s], lab, len(x), x.mean(), x.std(), x.min(), x.max(), within.std()])
desc = pd.DataFrame(rows, columns=["Size class", "Variable", "N", "Mean", "SD", "Min", "Max", "Within-country SD"])
desc.to_csv(OUT / "table1_descriptives.csv", index=False)
log(desc.round(2).to_string(index=False))

# EU-27 AI adoption by size and year, 2021-2025 (Eurostat EU aggregate)
eu_ai = eu.pivot_table(index="year", columns="size", values="ai_use")
eu25 = ai25[ai25["geo_code"] == "EU27_2020"].set_index("size")["ai_use"]
eu_ai.loc[2025] = [eu25[s] for s in eu_ai.columns]
eu_ai = eu_ai[SIZES].sort_index()
eu_ai["Gap large-small (pp)"] = eu_ai["GE250"] - eu_ai["10-49"]
eu_ai["Ratio large/small"] = eu_ai["GE250"] / eu_ai["10-49"]
eu_ai.to_csv(OUT / "table2_eu27_ai_by_size.csv")
log("\n2. EU-27 AI ADOPTION BY SIZE CLASS (% of enterprises, Eurostat EU aggregate)")
log(eu_ai.round(2).to_string())

# country ranking, small firms, 2025
c25 = (ai25[(ai25["geo_code"] != "EU27_2020")]
       .pivot_table(index=["geo_code", "country"], columns="size", values="ai_use")[SIZES]
       .reset_index().sort_values("10-49", ascending=False))
c25["Gap large-small (pp)"] = c25["GE250"] - c25["10-49"]
c25.to_csv(OUT / "table3_country_ai_2025.csv", index=False)
log("\n3. AI ADOPTION 2025 BY COUNTRY (% of enterprises), sorted by small firms")
log(c25.round(1).to_string(index=False))
log(f"\nCorrelation across countries, 2025, small-firm vs large-firm adoption: "
    f"{c25['10-49'].corr(c25['GE250']):.2f}")

# ------------------------------------------------------------ 2. FIGURES
plt.rcParams.update({"font.family": "serif", "font.size": 10})
fig, ax = plt.subplots(figsize=(6.5, 4))
for s, mk in zip(SIZES, ["o", "s", "^"]):
    ax.plot(eu_ai.index, eu_ai[s], marker=mk, color="black",
            linestyle={"10-49": "-", "50-249": "--", "GE250": ":"}[s], label=SIZE_LABEL[s])
    ax.annotate(f"{eu_ai.loc[2025, s]:.1f}", (2025, eu_ai.loc[2025, s]),
                textcoords="offset points", xytext=(6, -3), fontsize=9)
ax.set_xticks(eu_ai.index)
ax.set_ylabel("Enterprises using AI (%)")
ax.set_xlabel("Year (no survey in 2022)")
ax.legend(frameon=False)
ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
fig.savefig(OUT / "figure1_eu27_ai_by_size.png", dpi=300)
plt.close(fig)

fig, ax = plt.subplots(figsize=(6.5, 6.5))
cc = c25.sort_values("10-49")
y = np.arange(len(cc))
ax.barh(y, cc["10-49"], color="0.35", label="Small (10-49)")
ax.scatter(cc["GE250"], y, color="black", marker="|", s=120, label="Large (250+)", zorder=3)
ax.set_yticks(y)
ax.set_yticklabels(cc["country"])
ax.set_xlabel("Enterprises using AI, 2025 (%)")
ax.axvline(eu_ai.loc[2025, "10-49"], color="0.6", linestyle="--", linewidth=1)
ax.text(eu_ai.loc[2025, "10-49"] + 0.5, len(cc) - 0.5, "EU-27 small firms", fontsize=8, color="0.4")
ax.legend(frameon=False, loc="lower right")
ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
fig.savefig(OUT / "figure2_country_ai_2025.png", dpi=300)
plt.close(fig)

# ------------------------------------------------------------ 3. REGRESSIONS
FORMULA = "{y} ~ ai_use + dii_basic + gdp_growth + C(geo_code) + C(year)"


def fe(data, y):
    d = data.dropna(subset=[y, "ai_use", "dii_basic", "gdp_growth"]).copy()
    # countries need at least 2 observations to contribute within-country variation
    d = d[d.groupby("geo_code")["year"].transform("count") >= 2]
    m = smf.ols(FORMULA.format(y=y), data=d).fit(
        cov_type="cluster", cov_kwds={"groups": pd.factorize(d["geo_code"])[0]})
    # within R-squared: variance explained after removing country and year means
    base = smf.ols(f"{y} ~ C(geo_code) + C(year)", data=d).fit()
    within_r2 = 1 - m.ssr / base.ssr
    return m, d, within_r2


def stars(p):
    return "***" if p < 0.01 else "**" if p < 0.05 else "*" if p < 0.10 else ""


specs = {
    "Main": lambda d: d,
    "R1: 2021 and 2023 only (no carried-forward DII)": lambda d: d[d["year"].isin([2021, 2023])],
    "R2: excluding France and Sweden": lambda d: d[~d["geo_code"].isin(["FR", "SE"])],
}
outcomes = {"ln_lp": "ln real labour productivity", "ln_emp": "ln persons employed"}

rows = []
log("\n4. TWO-WAY FIXED EFFECTS REGRESSIONS (country and year FE; SE clustered by country)")
log("   Coefficients: effect of a 1 percentage-point higher AI use share on the log outcome.")
log("   x100 = approximate % change. *** p<0.01, ** p<0.05, * p<0.10")
for spec, f in specs.items():
    log(f"\n--- {spec} ---")
    for yv, ylab in outcomes.items():
        for s in SIZES:
            m, d, wr2 = fe(f(panel[panel["size"] == s]), yv)
            for v in ["ai_use", "dii_basic", "gdp_growth"]:
                rows.append([spec, ylab, SIZE_LABEL[s], v, m.params[v], m.bse[v], m.pvalues[v],
                             m.conf_int().loc[v, 0], m.conf_int().loc[v, 1],
                             int(m.nobs), d["geo_code"].nunique(), wr2])
            b, se, p = m.params["ai_use"], m.bse["ai_use"], m.pvalues["ai_use"]
            log(f"{ylab:<28} {SIZE_LABEL[s]:<16} AI: {b:8.4f}{stars(p):<3} (SE {se:.4f}, p={p:.3f}) "
                f"N={int(m.nobs):>3} countries={d['geo_code'].nunique()} within R2={wr2:.3f}")

reg = pd.DataFrame(rows, columns=["Specification", "Outcome", "Size class", "Variable", "Coefficient",
                                  "Clustered SE", "p-value", "CI 95% low", "CI 95% high",
                                  "N", "Countries", "Within R2"])
reg.to_csv(OUT / "table4_regressions_all.csv", index=False)

# compact main table: coefficient (SE) with stars, columns = size x outcome
main = reg[reg["Specification"] == "Main"].copy()
main["cell"] = [f"{c:.4f}{stars(p)} ({s:.4f})" for c, s, p in zip(main["Coefficient"], main["Clustered SE"], main["p-value"])]
wide = main.pivot_table(index="Variable", columns=["Outcome", "Size class"], values="cell", aggfunc="first")
foot = main.drop_duplicates(["Outcome", "Size class"]).set_index(["Outcome", "Size class"])[["N", "Countries", "Within R2"]].T
foot.loc["Within R2"] = foot.loc["Within R2"].astype(float).round(3)
wide = pd.concat([wide.reindex(["ai_use", "dii_basic", "gdp_growth"]), foot.astype(str)])
wide.to_csv(OUT / "table5_main_regressions.csv")

# ------------------------------------------------------------ 4. POWER NOTE
log("\n5. HOW MUCH VARIATION IS THERE TO ESTIMATE FROM?")
for s in SIZES:
    sub = panel[panel["size"] == s]
    within = (sub["ai_use"] - sub.groupby("geo_code")["ai_use"].transform("mean")).std()
    ch = sub.pivot_table(index="geo_code", columns="year", values="ai_use")
    log(f"{SIZE_LABEL[s]:<16} within-country SD of AI use: {within:.2f} pp; "
        f"mean change 2021-2024: {(ch[2024] - ch[2021]).mean():.2f} pp")

(OUT / "results_report.txt").write_text("\n".join(report), encoding="utf-8")
log("\nSaved to output/: table1-5 (CSV), figure1-2 (PNG), results_report.txt")
